#!/usr/bin/env python3
"""Build RULES.md, the one-line-per-rule digest, from PLAYBOOK.md.

A rule in PLAYBOOK.md is a paragraph that starts with "**R-<area>-<n>." The digest keeps the
first paragraph of each rule (the rule itself) and drops the Why / Check bullets and the
evidence tags. Run it after every edit of PLAYBOOK.md:

    python3 tools/make_rules_digest.py
"""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
lines = (root / "PLAYBOOK.md").read_text(encoding="utf-8").split("\n")

out = [
    "# Rules digest",
    "",
    "Every rule of [PLAYBOOK.md](PLAYBOOK.md) in one line, without the reasons. This is the file",
    "a coordinator agent loads; it opens the playbook section when it needs the why, the numbers",
    "or the check. Generated by `tools/make_rules_digest.py`: do not edit by hand.",
]
count = 0
pending_section = None
i = 0
while i < len(lines):
    line = lines[i]
    if re.match(r"^## \d+\. ", line):
        section = line
        pending_section = section
        i += 1
        continue
    if line.startswith("**R-"):
        para = [line]
        i += 1
        while i < len(lines) and lines[i].strip() and not re.match(r"^(- |\d+\. |\|)", lines[i]):
            para.append(lines[i])
            i += 1
        text = " ".join(p.strip() for p in para)
        text = re.sub(r"\s*`(\[[MIUPO]\])+`", "", text)
        text = re.sub(r"\s+([.,;:])", r"\1", text)
        if pending_section:
            out += ["", pending_section, ""]
            pending_section = None
        out.append("- " + text)
        count += 1
        continue
    i += 1

out.append("")
(root / "RULES.md").write_text("\n".join(out), encoding="utf-8")
print(f"RULES.md: {count} rules, {len(chr(10).join(out).encode())} bytes")
